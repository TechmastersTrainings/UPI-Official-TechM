"""Merchant webhook endpoint configuration (one per environment).

The signing secret is generated by the platform, encrypted at rest (it is needed to sign outgoing
events), and shown to the merchant only when created or rotated. `validated_at` is set when a
signed test event is acknowledged by the endpoint (webhook test, Phase 5/6); changing the URL
clears it."""

import secrets

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.config import get_settings
from app.core.crypto import encrypt_str
from app.core.errors import AppError, NotFound
from app.core.validators import validate_webhook_url
from app.models import User, WebhookConfiguration
from app.schemas.merchant import WebhookConfigUpsert
from app.services import audit
from app.services.audit import RequestMeta


def _new_secret() -> str:
    return "whsec_" + secrets.token_urlsafe(32)


def _validated_url(url: str, environment: str) -> str:
    try:
        return validate_webhook_url(url, environment=environment, allow_insecure_local=get_settings().is_dev_like)
    except ValueError as exc:
        raise AppError(f"Webhook URL {exc}", code="INVALID_WEBHOOK_URL") from exc


def list_for(db: Session, merchant_id: str) -> list[WebhookConfiguration]:
    return list(db.scalars(
        select(WebhookConfiguration).where(WebhookConfiguration.merchant_id == merchant_id)
        .order_by(WebhookConfiguration.environment)
    ))


def get_for(db: Session, merchant_id: str, environment: str) -> WebhookConfiguration | None:
    return db.scalar(select(WebhookConfiguration).where(
        WebhookConfiguration.merchant_id == merchant_id, WebhookConfiguration.environment == environment
    ))


def upsert(db: Session, merchant_id: str, environment: str, body: WebhookConfigUpsert, actor: User, meta: RequestMeta) -> tuple[WebhookConfiguration, str | None]:
    url = _validated_url(body.url, environment)
    events = sorted(set(body.events))
    cfg = get_for(db, merchant_id, environment)
    secret = None
    if cfg is None:
        secret = _new_secret()
        cfg = WebhookConfiguration(
            merchant_id=merchant_id, environment=environment, url=url, events=events, is_active=body.is_active,
            signing_secret_enc=encrypt_str(secret), secret_prefix=secret[:12],
        )
        db.add(cfg)
        db.flush()
        audit.record(db, "webhook_config.created", actor=actor, entity_type="webhook_config", entity_id=cfg.id,
                     merchant_id=merchant_id, details={"environment": environment, "url": url, "events": events}, meta=meta)
    else:
        changes: dict = {}
        if url != cfg.url:
            changes["url"] = [cfg.url, url]
            cfg.url = url
            cfg.validated_at = None
        if events != sorted(cfg.events):
            changes["events"] = [cfg.events, events]
            cfg.events = events
        if body.is_active != cfg.is_active:
            changes["is_active"] = [cfg.is_active, body.is_active]
            cfg.is_active = body.is_active
        if changes:
            audit.record(db, "webhook_config.updated", actor=actor, entity_type="webhook_config", entity_id=cfg.id,
                         merchant_id=merchant_id, details=changes, meta=meta)
    db.commit()
    db.refresh(cfg)
    return cfg, secret


def rotate_secret(db: Session, merchant_id: str, environment: str, actor: User, meta: RequestMeta) -> tuple[WebhookConfiguration, str]:
    cfg = get_for(db, merchant_id, environment)
    if cfg is None:
        raise NotFound("Webhook is not configured for this environment")
    secret = _new_secret()
    cfg.signing_secret_enc = encrypt_str(secret)
    cfg.secret_prefix = secret[:12]
    audit.record(db, "webhook_config.secret_rotated", actor=actor, entity_type="webhook_config", entity_id=cfg.id,
                 merchant_id=merchant_id, meta=meta)
    db.commit()
    db.refresh(cfg)
    return cfg, secret
